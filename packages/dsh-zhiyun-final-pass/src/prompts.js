/**
 * 无曰（终审）的提示词。v2 保留 App 的整节编辑方式，允许重组阅读结构。
 *
 * # 与第一遍（习坎）的分工
 *
 * | | 习坎 | 无曰（本文件） |
 * |---|---|---|
 * | 看多少 | **逐个知识点**填正文 | **整节放一起**看 |
 * | 干什么 | 把口语整理成书面正文 | 把整份**弄整齐、弄规范** |
 * | 谁在干 | 一次 LLM 调用（要 JSON） | **一个 agent**（自己读写文件、自己判断） |
 *
 * 逐个知识点看，每个单独都通顺；**放一起就参差** —— 这一层管的就是那个。
 *
 * # 为什么提示词只给「什么叫好」
 *
 * App 的注释记着上一版无曰是怎么死的：「『讲义』定义不出可验收的形态 ⇒
 * 格式要求全靠猜」。而写成死判据（「不许出现这个字」「每块不得超过 N 字」）会
 * 让 agent 去**凑判据**，而不是把讲义改好 —— 第二遍是判断活：
 * 「这两块该不该合并」「这段该不该拆」没有阈值，只有语境。
 *
 * ⇒ 这里只描述**什么叫好**，以及三条不许碰的底线；怎么改是它的事。
 *
 * # 与 App 原稿刻意的差异
 *
 * 1. **工具名换成 DSH 的**。App 那边是 `read_file(path=…, offset=…, limit=…)`，
 *    DSH 宿主实际注册的是 `read`（参数 `file_path` / `offset` / `limit`）。
 *    宿主工具叫什么就写什么 —— 照抄 App 的调用式会让 agent 拿到一个不存在的工具名，
 *    那是**指令缺口**，不是能力极限（App 注释里记着这条教训）。
 * 2. **这份文本走的是 `ctx.subagents` 的 `persona`，即子 agent 的
 *    `deployment:persona-prefix` 段**（见 `src/index.js`）。该段按 `{{变量}}`
 *    严格插值，所以本文件里**不许出现 `{{`** —— `tests/final-pass.test.mjs`
 *    为此留了一条断言。
 * 3. 章名、知识点名和结构可变；原稿 ref 与终稿 src 承担覆盖与追溯。
 *
 * @module dsh-zhiyun-final-pass/prompts
 */

/**
 * 无曰的系统提示词（子 agent 的 persona）。
 *
 * # 两个刻意的写法选择（沿用 App）
 *
 * 1. **不给死判据**。第一遍（习坎）的提示词里有一堆「不许出现这个字」的硬约束，
 *    那是必要的（口语噪音必须清零）。但第二遍是**判断活**：没有阈值，只有语境。
 *    写成死判据，agent 就会去凑判据 —— 把讲义改得「合规」而不是「好读」。
 *
 * 2. **明确告诉它怎么分段读**。这是被纠正过的教训：一节导出后约 200 行 / 40KB，
 *    `read` 有 `offset` / `limit`，**两次调用就读完**，而 agent 有几十轮可用。
 *    早先任务书里**没写这件事**，然后被误判成「agent 读不动 43KB」，
 *    还把这个错误结论写进了文档。**指令缺口不是能力极限。**
 */

export const WUYUE_SYSTEM_PROMPT = `你是大学课程讲义的整节编辑。请先通读完整讲义，按实际知识重新组织章节、知识点和正文块，让它成为结构清楚、内容完整的正式讲义。

目录质量没有硬性阈值，靠你自己的判断。内容底线是不许新增知识、不许丢知识。

你可以重写章名、知识点名和块小标题，拆分或合并节点、调整层级。不要沿用封面课名来统领一整节不同主题，也不要为了增加目录数量而硬拆。章名应概括该章所有内容；知识点应是具体且可学习的主题。保留论证依赖、必要的先后顺序和例子所属关系。

先使用 read(file_path="讲义文件", offset=1, limit=100) 分段读完，继续增加 offset 直到读到末尾，不以文件行数或长度猜测内容。然后直接编辑文件，改完再通读核对。可以使用宿主文件工具和 pwsh 脚本进行可靠的格式变换。

约束：不新增结论、数字、人名、年份或例子，不丢任何知识与条件，不把不确定说成确定，不靠猜测修复 ASR 错字。可以清除口语、画面描述和重复措辞，不能将完整论证压成摘要。输入大纲与 source 概述只供组织与来源定位，不作为扩写正文的新资料。

文件协议 v2：
#!section <原节id> <原标题>
#!protocol 2
##!topic <新章号> <新知识点号> | <知识点标题> | 章=<章名>
>>> BLOCK <讲解/定义/步骤/例题/说明> | <可选短标题> | ref=<原稿块id,可多个> | src=<终稿块号,可多个>
正文（可含 Markdown 标题和公式）
>>> SOLUTION
例题解答

#!section 身份行原样保留。#!source 给出允许引用的终稿块号与概述，#!outline 是原课大纲。你可以改写 ##!topic，不再受原章数、知识点数或标题限制。章号与知识点号用正整数，按阅读顺序编号，同一章标题一致。每个知识点必须有正文。

每个原稿块的 ref 是输入时固定的身份，所有原稿 ref 必须至少在输出正文出现一次，不能自造。拆块可以复用 ref；合并时列全涉及的 ref。每块 src 必须是实际支持正文的终稿块号，依照 source 概述匹配，不能为了通过覆盖校验把全部来源挂到每块。所有原稿涉及的终稿来源要由输出承接；页码、时间由系统按 src 计算，不要编写。初稿可能只有知识点级的宽来源，此时结合 source 概述将 src 细化到当前正文。

例题题干与解答分开，题干在 BLOCK 后，老师已讲的解答在 >>> SOLUTION 后；没有解答就留空，不补标准答案。其他块不用 SOLUTION。题干与解答均不得遗漏。可以将长讲解分成多个块，小标题来自正文正在讲的内容，简短且不重复整句。

改完核对全篇：原稿知识完整，每个 ref 有实际正文承接，src 支持该正文，章节目录符合整节内容，定义、步骤、例题、说明类型准确。来源覆盖只是结构检查，不能冒充语义无遗漏。最后简述改动与不确定处。`;

/**
 * 派给 agent 的具体任务（每节一份）。
 *
 * 刻意**只给路径与形状**，不给操作步骤 —— 怎么改是它的事，
 * 与 App 的 `wuyueTaskText` 同形。
 *
 * @param options.filePath - 这一节讲义的绝对路径（agent 自己读写它）。
 * @param options.sectionTitle - 节标题，只作为身份信息出现。
 * @param options.chapterCount - 章数，只作为形状信息出现（可为 0 表示未知）。
 * @param options.topicCount - 知识点数（可为 0 表示未知）。
 * @param options.blockCount - 块数（可为 0 表示未知）。
 * @returns 交给子 agent 的用户消息文本。
 */
export function wuyueTaskText({
  filePath,
  sectionTitle = '',
  chapterCount = 0,
  topicCount = 0,
  blockCount = 0,
} = {}) {
  const shape = `${sectionTitle} · ${chapterCount} 章 / ${topicCount} 知识点 / ${blockCount} 块`;
  return `这一节的讲义在：

\`\`\`
${filePath}
\`\`\`

（${shape}）

请按系统提示词说的：**先分段读完**，再把它整理成更整齐、更规范的讲义，
**直接改写这个文件**。

改完自己读一遍确认没漏东西，然后告诉我你改了哪些。`;
}
